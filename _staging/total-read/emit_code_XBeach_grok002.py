def extract_python(lines: list[str], path: str) -> dict:
    entities = []
    constants = []
    calls = []
    io = []
    verbatim = []
    params_defined = []
    re_class = re.compile(r"^class\s+(\w+)")
    re_def = re.compile(r"^(\s*)def\s+(\w+)\s*\(")
    re_async = re.compile(r"^(\s*)async\s+def\s+(\w+)\s*\(")
    for i, line in enumerate(lines, 1):
        m = re_class.match(line)
        if m:
            entities.append(f"class {m.group(1)} (L{i})")
        m = re_def.match(line) or re_async.match(line)
        if m:
            indent, name = m.group(1), m.group(2)
            kind = "method" if indent else "function"
            entities.append(f"{kind} {name} (L{i})")
        # module-level setup(...) is the only entry in distutils scripts
        if re.match(r"^setup\s*\(", line):
            entities.append(f"call setup (L{i})")
        # module-level assignment of simple constants
        m = re.match(r"^([A-Z][A-Z0-9_]*)\s*=\s*(.+)$", line)
        if m:
            constants.append({"name": m.group(1), "value": m.group(2).strip()[:120], "line": i})
        m = re.match(r"^([a-z_][a-z0-9_]*)\s*=\s*([0-9]+|['\"].*['\"]|True|False|None)\s*$", line)
        if m and m.group(1) in ("version", "dllsuffix") or (
            m and not m.group(1).startswith("_") and m.group(1) in ("WD",)
        ):
            constants.append({"name": m.group(1), "value": m.group(2).strip()[:120], "line": i})
        if re.match(r"^(import |from )", line):
            calls.append(f"{line.strip()} (L{i})")
        if "open(" in line or "with open" in line:
            io.append(f"{line.strip()[:140]} (L{i})")

    bn = os.path.basename(path)
    if bn == "makedepo.py":
        what = (
            "Python Fortran dependency scanner: parses module/use/include lines from source args; "
            "outputs make rules in modes O:FHO/O:FH/O:M/M:F via -m/-p/-s options."
        )
    elif bn == "generate.py":
        what = (
            "XBeach Fortran source generator: parses variables.def/params.def with regex, maps Fortran types, "
            "renders mako templates under xbeachlibrary/templates to .inc files; requires mako package."
        )
    elif bn == "libxbeach.py":
        what = (
            "Python ctypes proxy class XBeach for libxbeach shared library: init/executestep/output, "
            "parameter get/set, array get/set by rank/type, finalize with dlclose; platform dllsuffix map."
        )
    elif bn == "test_libxbeach.py":
        what = (
            "unittest suite TestXBeach and IntegrationTest for libxbeach.XBeach proxy against example1 data; "
            "tests parameter/array APIs, executestep, and rewind consistency."
        )
    elif bn == "setup.py" and "scripts" in path:
        what = "distutils/py2exe setup for packaging scripts/generate.py as console exe with pygments.styles.default include."
    elif bn == "setup.py":
        what = (
            "setuptools setup for pybeach package 'XBeach' v0.1 (Fedor Baart): numpy/matplotlib/nose deps, GPLv3."
        )
    elif bn == "__init__.py":
        what = f"Empty Python package marker ({path})."
    else:
        what = f"Python file {bn}, {len(lines)} lines, {len(entities)} defs/classes."

    for i, line in enumerate(lines, 1):
        if '"""' in line or "'''" in line:
            verbatim.append({"text": line.strip()[:200], "loc": i})
            if len(verbatim) >= 2:
                break
    if not verbatim and lines:
        verbatim.append({"text": (lines[0] if lines else "")[:200], "loc": 1 if lines else 0})

    return dict(
        what_it_is=what,
        entities=entities,
        constants=constants,
        params_defined=params_defined,
        equations=[],
        io=io,
        calls=calls[:40],
        verbatim_spans=verbatim[:5],
        unresolved=[],
    )


def extract_fortran_src(lines: list[str], path: str) -> dict:
    entities = []
    constants = []
    calls = []
    io = []
    verbatim = []
    re_mod = re.compile(r"^\s*module\s+(\w+)", re.I)
    re_prog = re.compile(r"^\s*program\s+(\w+)", re.I)
    re_sub = re.compile(r"^\s*(?:recursive\s+)?(?:pure\s+)?(?:elemental\s+)?subroutine\s+(\w+)", re.I)
    re_fn = re.compile(
        r"^\s*(?:(?:integer|real|logical|character|double\s+precision|type)(?:\([^)]*\))?\s+)?"
        r"(?:recursive\s+)?(?:pure\s+)?function\s+(\w+)",
        re.I,
    )
    re_fn2 = re.compile(
        r"^\s*([\w()*=]+)\s+function\s+(\w+)", re.I
    )
    re_use = re.compile(r"^\s*use\s+(\w+)", re.I)
    re_call = re.compile(r"^\s*call\s+(\w+)", re.I)
    for i, line in enumerate(lines, 1):
        s = line.split("!")[0]
        m = re_mod.match(s)
        if m:
            entities.append(f"module {m.group(1)} (L{i})")
        m = re_prog.match(s)
        if m:
            entities.append(f"program {m.group(1)} (L{i})")
        m = re_sub.match(s)
        if m:
            entities.append(f"subroutine {m.group(1)} (L{i})")
        m = re_fn.match(s)
        if m:
            entities.append(f"function {m.group(1)} (L{i})")
        else:
            m = re_fn2.match(s)
            if m and m.group(2).lower() not in ("end",):
                entities.append(f"function {m.group(2)} (L{i})")
        m = re_use.match(s)
        if m:
            calls.append(f"use {m.group(1)} (L{i})")
        m = re_call.match(s)
        if m:
            calls.append(f"call {m.group(1)} (L{i})")
        if "write(" in s.lower() or "read(" in s.lower() or "print" in s.lower():
            io.append(f"{s.strip()[:120]} (L{i})")
        if "Welcome to XBeach" in line or "XBeach version" in line:
            verbatim.append({"text": line.strip()[:200], "loc": i})

    bn = os.path.basename(path)
    if bn == "input.F90":
        what = (
            "Fortran module process_input: function readinput() parses CLI (-V version banner, -h/--help usage) "
            "via command_argument_count/get_command_argument; returns c_int 1 to signal early exit."
        )
    elif bn == "xbeach.F90":
        what = (
            "Main program xbeach: readinput → init → time loop (executestep/outputext while t<tstop via "
            "getdoubleparameter) → final; uses libxbeach_module, introspection_module, process_input, xmpi_module."
        )
    else:
        what = f"Fortran source {bn}, {len(lines)} lines."

    if not verbatim and lines:
        verbatim.append({"text": lines[0].strip()[:200], "loc": 1})
    return dict(
        what_it_is=what,
        entities=entities,
        constants=constants,
        params_defined=[],
        equations=[],
        io=io,
        calls=calls,
        verbatim_spans=verbatim[:5],
        unresolved=[],
    )


def extract_makefile(lines: list[str], path: str) -> dict:
    entities = []
    constants = []
    calls = []
    io = []
    verbatim = []
    for i, line in enumerate(lines, 1):
        s = line.strip()
        if not s or s.startswith("#"):
            if s.startswith("#") and len(verbatim) < 2:
                verbatim.append({"text": s[:200], "loc": i})
            continue
        m = re.match(r"^([A-Za-z_][\w]*)\s*([:+]?=)\s*(.*)$", line)
        if m and not line.startswith("\t"):
            name, op, val = m.group(1), m.group(2), m.group(3).strip()
            constants.append({"name": name, "value": val[:200], "line": i})
            entities.append(f"var {name} (L{i})")
        m = re.match(r"^([A-Za-z_][\w%-]*)\s*:", line)
        if m and not line.startswith("\t"):
            entities.append(f"target {m.group(1)} (L{i})")
        if s.startswith("include ") or s.startswith("$(MAKE)") or s.startswith("$(MAKEDEPO)"):
            calls.append(f"{s[:120]} (L{i})")
        if "SUBDIRS" in s or "bin_PROGRAMS" in s or "SOURCES" in s:
            io.append(f"{s[:140]} (L{i})")

    bn = path
    if bn.endswith("src/Makefile.am"):
        what = "Automake for src/: SUBDIRS=xbeachlibrary xbeach; dep/depclean recurse into both."
    elif bn.endswith("xbeach/Makefile.am"):
        what = (
            "Automake for bin xbeach: sources input.F90 xbeach.F90, links libxbeach.la; "
            "USEMPI/USENETCDF conditionals; depclean/dep via MAKEDEPO."
        )
    else:
        what = f"Makefile/Automake {os.path.basename(path)}, {len(lines)} lines."
    if not verbatim and lines:
        verbatim.append({"text": lines[0].strip()[:200], "loc": 1})
    return dict(
        what_it_is=what,
        entities=entities,
        constants=constants,
        params_defined=[],
        equations=[],
        io=io,
        calls=calls,
        verbatim_spans=verbatim[:5],
        unresolved=[],
    )


def extract_shell(lines: list[str], path: str) -> dict:
    entities = []
    constants = []
    calls = []
    io = []
    verbatim = []
    for i, line in enumerate(lines, 1):
        s = line.strip()
        if s.startswith("#") and len(verbatim) < 3:
            verbatim.append({"text": s[:200], "loc": i})
        m = re.match(r"^(?:export\s+)?([A-Za-z_][\w]*)=(.*)$", s)
        if m and not s.startswith("rem ") and not s.lower().startswith("set "):
            constants.append({"name": m.group(1), "value": m.group(2).strip()[:120], "line": i})
        # bat set VAR=
        m = re.match(r"set\s+([A-Za-z_][\w]*)=(.*)$", s, re.I)
        if m:
            constants.append({"name": m.group(1), "value": m.group(2).strip()[:120], "line": i})
            entities.append(f"var {m.group(1)} (L{i})")
        for cmd in ("rm", "rmdir", "mkdir", "copy", "xcopy", "del", "find", "grep", "7za", "cd"):
            if re.search(rf"\b{cmd}\b", s, re.I):
                calls.append(f"{s[:120]} (L{i})")
                break
        if "rm -f" in s or "copy " in s.lower() or "mkdir " in s.lower():
            io.append(f"{s[:140]} (L{i})")

    bn = os.path.basename(path)
    if bn == "mpi_filter":
        what = "Bash one-liner filter: grep -v 'warning:.*mpi_' then exit 0; strips MPI-related compiler warnings."
        entities.append("script mpi_filter (L1)")
    elif bn == "rmdiv":
        what = (
            "Bash cleanup: removes autoconf-generated Makefile.in, configure, libtool, aclocal.m4, "
            "config/*, and m4 libtool suite files."
        )
        entities.append("script rmdiv (L1)")
    elif bn == "distribute.bat":
        what = (
            "Windows bat: clears dist/<Platform>/<Config>, copies static dlls into TargetDir, "
            "copies exe/dll into dist, copies manual PDF and LICENSE."
        )
    elif bn == "zip.bat":
        what = (
            "Windows bat: copies 7za.exe into dist folder, creates xbeach_<Config>_<Platform>.zip of all files, "
            "removes 7za.exe from archive and disk."
        )
    else:
        what = f"Shell/batch script {bn}, {len(lines)} lines."
    if not verbatim and lines:
        verbatim.append({"text": lines[0].strip()[:200], "loc": 1})
    return dict(
        what_it_is=what,
        entities=entities,
        constants=constants,
        params_defined=[],
        equations=[],
        io=io,
        calls=calls,
        verbatim_spans=verbatim[:5],
        unresolved=[],
    )


def extract_text(lines: list[str], path: str) -> dict:
    entities = []
    constants = []
    io = []
    verbatim = []
    bn = os.path.basename(path)
    if bn == "DEPENDENCIES.txt":
        what = (
            "py2exe dependency notice listing system DLLs (OLEAUT32, USER32, SHELL32, ole32, ADVAPI32, "
            "WS2_32, GDI32, VERSION, KERNEL32) not bundled with the executable."
        )
        for i, line in enumerate(lines, 1):
            m = re.search(r"(\w+\.dll)\s*-\s*(.+)", line, re.I)
            if m:
                entities.append(f"dll {m.group(1)} (L{i})")
                constants.append({"name": m.group(1), "value": m.group(2).strip(), "line": i})
    elif bn == "info.txt":
        what = (
            "Notes on building generate.py executable: (1) py2exe+setup.py failed 5-9-2019; "
            "(2) use pyinstaller generate.py → dist/generate/*."
        )
        entities.append("doc info.txt")
    elif bn == "setup.cfg":
        what = "setuptools egg_info config: tag_build=dev, tag_svn_revision=true."
        for i, line in enumerate(lines, 1):
            m = re.match(r"(\w+)\s*=\s*(.*)", line)
            if m:
                constants.append({"name": m.group(1), "value": m.group(2).strip(), "line": i})
                entities.append(f"key {m.group(1)} (L{i})")
        if lines and lines[0].startswith("["):
            entities.insert(0, f"section {lines[0].strip()} (L1)")
    else:
        what = f"Text file {bn}, {len(lines)} lines."
        entities.append(f"file {bn}")
    if lines:
        verbatim.append({"text": lines[0].strip()[:200], "loc": 1})
        if len(lines) > 1:
            verbatim.append({"text": lines[-1].strip()[:200], "loc": len(lines)})
    return dict(
        what_it_is=what,
        entities=entities,
        constants=constants,
        params_defined=[],
        equations=[],
        io=io,
        calls=[],
        verbatim_spans=verbatim,
        unresolved=[],
    )


def extract_xml(lines: list[str], path: str) -> dict:
    entities = []
    constants = []
    io = []
    verbatim = []
    text = "\n".join(lines)
    bn = os.path.basename(path)
    # tags
    for i, line in enumerate(lines, 1):
        for m in re.finditer(r"<(\w+)([^>]*)>", line):
            tag, attrs = m.group(1), m.group(2)
            if tag.startswith("?"):
                continue
            if tag in ("VisualStudioProject", "Platform", "Configuration", "Tool", "File",
                       "assembly", "assemblyIdentity", "dependentAssembly", "supportedOS",
                       "dependency", "compatibility", "application"):
                name_m = re.search(r'Name="([^"]+)"', attrs)
                id_m = re.search(r'Id="([^"]+)"', attrs)
                n_m = re.search(r'name="([^"]+)"', attrs)
                label = name_m.group(1) if name_m else (n_m.group(1) if n_m else (id_m.group(1) if id_m else tag))
                entities.append(f"xml {tag}:{label} (L{i})")
            if "Include=" in attrs:
                im = re.search(r'Include="([^"]+)"', attrs)
                if im:
                    io.append(f"Include {im.group(1)} (L{i})")
            for km in re.finditer(r'(\w+)="([^"]*)"', attrs):
                if km.group(1) in ("Version", "ProjectIdGuid", "Keyword", "ProjectCreator",
                                   "processorArchitecture", "publicKeyToken", "type", "version",
                                   "manifestVersion"):
                    constants.append({"name": f"{tag}.{km.group(1)}", "value": km.group(2)[:120], "line": i})

    if bn.endswith(".manifest"):
        what = (
            "Windows side-by-side assembly manifest for generate.exe: amd64 win32 identity, depends on "
            "Microsoft.Windows.Common-Controls v6, lists supportedOS GUIDs (Vista through Windows 10)."
        )
    elif bn.endswith(".vfproj"):
        what = (
            f"Intel Fortran Visual Studio project for xbeach Console Application v11.0; platforms Win32/x64; "
            f"{len(lines)} lines of configurations/tools/files."
        )
    else:
        what = f"XML file {bn}, {len(lines)} lines."
    if lines:
        verbatim.append({"text": lines[0].strip()[:200], "loc": 1})
    # dedupe entities somewhat
    seen = set()
    ent2 = []
    for e in entities:
        if e not in seen:
            seen.add(e)
            ent2.append(e)
    return dict(
        what_it_is=what,
        entities=ent2,
        constants=constants,
        params_defined=[],
        equations=[],
        io=io[:50],
        calls=[],
        verbatim_spans=verbatim[:5],
        unresolved=[],
    )


