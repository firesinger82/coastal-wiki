def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_text(p: Path) -> tuple[str, list[str], str]:
    """Return (text, lines, read_status note). Always tries utf-8 then latin-1."""
    raw = p.read_bytes()
    for enc in ("utf-8", "latin-1", "cp1252"):
        try:
            text = raw.decode(enc)
            lines = text.splitlines()
            # preserve trailing empty line count like wc -l
            if text.endswith("\n") or text.endswith("\r\n"):
                # splitlines drops final empty; wc -l counts newline-terminated lines
                pass
            # Use exact wc -l semantics: count of newline characters
            return text, lines, "complete"
        except UnicodeDecodeError:
            continue
    return "", [], "failed"


def wc_l(p: Path) -> int:
    # match `wc -l`
    data = p.read_bytes()
    if not data:
        return 0
    return data.count(b"\n")


