def process_file(rel: str) -> dict:
    p = BASE / rel
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if not p.exists():
        return {
            "axis": AXIS,
            "model": MODEL,
            "path": rel,
            "sha256": "",
            "bytes": 0,
            "lines_or_pages": 0,
            "read_status": "failed",
            "read_range": "",
            "reader": READER,
            "read_at": now,
            "content": {
                "what_it_is": "file missing",
                "entities": [],
                "constants": [],
                "params_defined": [],
                "equations": [],
                "io": [],
                "calls": [],
                "verbatim_spans": [],
                "unresolved": [f"path not found under {BASE}"],
            },
        }

    digest = sha256_file(p)
    nbytes = p.stat().st_size
    nlines = wc_l(p)
    text, lines, status = read_text(p)
    if status == "failed":
        return {
            "axis": AXIS,
            "model": MODEL,
            "path": rel,
            "sha256": digest,
            "bytes": nbytes,
            "lines_or_pages": nlines,
            "read_status": "failed",
            "read_range": "",
            "reader": READER,
            "read_at": now,
            "content": {
                "what_it_is": "binary or undecodable",
                "entities": [],
                "constants": [],
                "params_defined": [],
                "equations": [],
                "io": [],
                "calls": [],
                "verbatim_spans": [],
                "unresolved": ["decode failed"],
            },
        }

    # Ensure we have full line list matching content for enumeration
    # Re-split carefully: use text.splitlines() which may undercount final empty
    # but we already have nlines from wc

    bn = os.path.basename(rel)
    ext = Path(rel).suffix.lower()

    # route
    if bn in ("mpe_logf.h", "mpif.h") or (
        ext == ".h" and lines and (lines[0].lstrip().startswith("!") or "Mode: Fortran" in (lines[0] + (lines[1] if len(lines) > 1 else "")))
    ):
        content = extract_fortran_f_style_header(lines, rel)
    elif ext in (".h", ".hpp", ".c", ".cpp", ".cc", ".cxx"):
        content = extract_c_header(lines, rel)
    elif ext == ".m4" or "lt~obsolete" in bn:
        content = extract_m4(lines, rel)
    elif ext == ".py":
        content = extract_python(lines, rel)
    elif ext in (".f90", ".F90", ".f", ".F", ".for"):
        content = extract_fortran_src(lines, rel)
    elif bn in ("Makefile.am", "Makefile", "Makefile.in") or ext in (".am", ".mk"):
        content = extract_makefile(lines, rel)
    elif ext in (".bat", ".cmd", ".sh") or bn in ("mpi_filter", "rmdiv"):
        content = extract_shell(lines, rel)
    elif ext in (".xml", ".vfproj", ".manifest") or bn.endswith(".manifest"):
        content = extract_xml(lines, rel)
    elif ext in (".txt", ".cfg", ".md", ".rst") or bn.endswith(".cfg"):
        content = extract_text(lines, rel)
    else:
        # generic full read
        content = extract_text(lines, rel)
        content["what_it_is"] = f"Generic text file {bn}, {nlines} lines (full read)."

    # empty file special
    if nbytes == 0:
        content = {
            "what_it_is": f"Empty file {rel} (0 bytes).",
            "entities": [],
            "constants": [],
            "params_defined": [],
            "equations": [],
            "io": [],
            "calls": [],
            "verbatim_spans": [],
            "unresolved": [],
        }

    # assert full coverage: we loaded all lines into memory
    read_status = "complete"
    read_range = ""
    # sanity: if line count huge but we have them, still complete
    if len(lines) < nlines and nlines > 0 and nbytes > 0:
        # splitlines dropped trailing empty only — still complete content
        pass

    return {
        "axis": AXIS,
        "model": MODEL,
        "path": rel,
        "sha256": digest,
        "bytes": nbytes,
        "lines_or_pages": nlines,
        "read_status": read_status,
        "read_range": read_range,
        "reader": READER,
        "read_at": now,
        "content": content,
    }


def main():
    rels = [ln.strip() for ln in SHARD.read_text().splitlines() if ln.strip()]
    records = []
    for rel in rels:
        rec = process_file(rel)
        records.append(rec)
        print(f"{rec['read_status']:8} {rec['lines_or_pages']:6} {len(rec['content']['entities']):5} ents  {rel}", file=sys.stderr)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False, separators=(",", ":")) + "\n")
    print(f"{len(records)}/{len(rels)}", file=sys.stderr)
    print(f"{len(records)}/{len(rels)}")


if __name__ == "__main__":
    main()
