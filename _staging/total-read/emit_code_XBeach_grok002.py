def _collapse_continued(lines):
    """Join lines that look like continued C prototypes."""
    out = []
    buf = None
    buf_i = 0
    for i, line in enumerate(lines, 1):
        s = line.rstrip()
        if buf is not None:
            buf = buf + " " + s.strip()
            if ";" in s or "{" in s:
                out.append((buf_i, buf))
                buf = None
            continue
        st = s.strip()
        if (
            st
            and not st.startswith("#")
            and not st.startswith("*")
            and not st.startswith("//")
            and "(" in s
            and ")" not in s
            and not st.endswith("\\")
            and re.match(r"^\s*(?:extern\s+)?[A-Za-z_].*", s)
        ):
            buf = s
            buf_i = i
            continue
        out.append((i, s))
    if buf is not None:
        out.append((buf_i, buf))
    return out


def extract_c_header(lines, path):
    entities = []
    constants = []
    calls = []
    io = []
    verbatim = []
    unresolved = []
    params_defined = []
    equations = []
    seen = set()

    re_def = re.compile(r"^\s*#\s*define\s+(\w+)(?:\s+(.*))?$")
    re_include = re.compile(r'^\s*#\s*include\s+[<\"]([^>\"]+)[>\"]')
    re_namespace = re.compile(r"^\s*namespace\s+(\w+)")
    re_class = re.compile(r"^\s*class\s+(\w+)")
    re_struct = re.compile(r"^\s*(?:typedef\s+)?struct\s+(\w+)")
    re_enum = re.compile(r"^\s*(?:typedef\s+)?enum\s+(\w+)")
    re_typedef = re.compile(r"^\s*typedef\s+.+\s+(\w+)\s*;")
    re_method = re.compile(
        r"^\s+(?:virtual\s+)?(?:static\s+)?(?:inline\s+)?"
        r"(?:const\s+)?[\w:<>\*&]+\s+(\w+)\s*\([^;]*\)\s*(?:const)?\s*;"
    )

    joined = _collapse_continued(lines)
    for i, line in joined:
        m = re_def.match(line)
        if m:
            name, val = m.group(1), (m.group(2) or "").strip()
            constants.append({"name": name, "value": val[:200], "line": i})
            key = f"#define {name}"
            if key not in seen:
                entities.append(f"#define {name} (L{i})")
                seen.add(key)
            continue
        m = re_include.match(line)
        if m:
            io.append(f"#include {m.group(1)} (L{i})")
            continue
        m = re_namespace.match(line)
        if m:
            key = f"namespace {m.group(1)}"
            if key not in seen:
                entities.append(f"namespace {m.group(1)} (L{i})")
                seen.add(key)
            continue
        m = re_class.match(line)
        if m:
            key = f"class {m.group(1)}"
            if key not in seen:
                entities.append(f"class {m.group(1)} (L{i})")
                seen.add(key)
            continue
        m = re_struct.match(line)
        if m and m.group(1):
            key = f"struct {m.group(1)}"
            if key not in seen:
                entities.append(f"struct {m.group(1)} (L{i})")
                seen.add(key)
            continue
        m = re_enum.match(line)
        if m and m.group(1):
            key = f"enum {m.group(1)}"
            if key not in seen:
                entities.append(f"enum {m.group(1)} (L{i})")
                seen.add(key)
            continue
        m = re_typedef.match(line)
        if m:
            key = f"typedef {m.group(1)}"
            if key not in seen:
                entities.append(f"typedef {m.group(1)} (L{i})")
                seen.add(key)
            continue
        m = re_method.match(line)
        if m:
            name = m.group(1)
            key = f"fn {name}"
            if key not in seen:
                entities.append(f"method {name} (L{i})")
                seen.add(key)
            continue
        if "(" in line and not line.strip().startswith("#") and not line.strip().startswith("*"):
            core = line.split("//")[0]
            if re.search(r"\)\s*;", core) or re.search(r"\)\s*\{", core) or re.search(r"\)\s*const\s*;", core):
                m2 = re.search(r"([A-Za-z_]\w*)\s*\([^;{]*\)\s*(?:const)?\s*[;{]", core)
                if not m2:
                    m2 = re.search(r"([A-Za-z_]\w*)\s*\(", core)
                if m2:
                    name = m2.group(1)
                    if name not in ("if", "for", "while", "switch", "return", "sizeof", "defined", "catch"):
                        key = f"fn {name}"
                        if key not in seen:
                            entities.append(f"function {name} (L{i})")
                            seen.add(key)

    # also scan original lines for class/method without collapse
    re_cxx_method = re.compile(
        r"^\s+(?:virtual\s+)?(?:static\s+)?(?:inline\s+)?"
        r"(?:explicit\s+)?"
        r"(?:const\s+)?(?:unsigned\s+|signed\s+)?"
        r"(?:[\w:<>\*&\s]+?\s+)"
        r"([A-Za-z_]\w*)\s*\("
    )
    re_ctor = re.compile(r"^\s+(?:explicit\s+)?(~?[A-Za-z_]\w*)\s*\(")
    for i, line in enumerate(lines, 1):
        m = re_class.match(line)
        if m:
            key = f"class {m.group(1)}"
            if key not in seen:
                entities.append(f"class {m.group(1)} (L{i})")
                seen.add(key)
        m = re_method.match(line)
        if m:
            name = m.group(1)
            key = f"fn {name}"
            if key not in seen:
                entities.append(f"method {name} (L{i})")
                seen.add(key)
            continue
        # C++ methods with body: "virtual void Barrier( void ) const" (no trailing ;)
        st = line.strip()
        if st.startswith(("if", "for", "while", "switch", "return", "case", "else", "typedef", "using", "friend", "enum", "struct", "class", "namespace", "public:", "private:", "protected:", "#", "//", "*", "{", "}")):
            continue
        if "(" not in line:
            continue
        m = re_cxx_method.match(line)
        if m:
            name = m.group(1)
            if name not in ("if", "for", "while", "switch", "return", "sizeof", "MPI_CHECK", "MPIX_CALL", "MPIX_CALLREF"):
                key = f"fn {name}"
                if key not in seen:
                    entities.append(f"method {name} (L{i})")
                    seen.add(key)
            continue
        # constructors / destructors: ClassName( or ~ClassName(
        m = re_ctor.match(line)
        if m and m.group(1)[0].isupper() or (m and m.group(1).startswith("~")):
            name = m.group(1)
            key = f"fn {name}"
            if key not in seen:
                entities.append(f"ctor {name} (L{i})")
                seen.add(key)

    what = describe_c(path, lines, entities, constants)
    for i, line in enumerate(lines, 1):
        if any(k in line for k in ("COPYRIGHT", "MPICH", "ROMIO", "Version", "buildiface")):
            verbatim.append({"text": line.strip()[:200], "loc": i})
            if len(verbatim) >= 4:
                break
    if not verbatim and lines:
        verbatim.append({"text": lines[0].strip()[:200], "loc": 1})

    return dict(
        what_it_is=what,
        entities=entities,
        constants=constants,
        params_defined=params_defined,
        equations=equations,
        io=io[:80],
        calls=calls,
        verbatim_spans=verbatim,
        unresolved=unresolved,
    )


def extract_fortran_include(lines, path):
    entities = []
    constants = []
    verbatim = []
    io = []
    seen = set()
    for i, line in enumerate(lines, 1):
        s = line.strip()
        for m in re.finditer(r"PARAMETER\s*\((.+)\)", line, re.I):
            body = m.group(1)
            for mm in re.finditer(r"(\w+)\s*=\s*([^,]+)", body):
                name, val = mm.group(1), mm.group(2).strip()
                constants.append({"name": name, "value": val, "line": i})
                key = f"param {name}"
                if key not in seen:
                    entities.append(f"parameter {name} (L{i})")
                    seen.add(key)
        m = re.match(r"(?:integer\s+)?external\s+(\w+)", s, re.I)
        if m:
            key = f"ext {m.group(1)}"
            if key not in seen:
                entities.append(f"external {m.group(1)} (L{i})")
                seen.add(key)
        m = re.match(r"integer\s+(\w+)", s, re.I)
        if m:
            name = m.group(1)
            key = f"int {name}"
            if key not in seen and f"param {name}" not in seen:
                entities.append(f"integer {name} (L{i})")
                seen.add(key)
        if re.search(r"\bcommon\b", s, re.I):
            entities.append(f"common (L{i}): {s[:100]}")
        if re.search(r"\bsave\b", s, re.I):
            entities.append(f"save (L{i}): {s[:100]}")
        if s.startswith("!") and any(k in s for k in ("Mode:", "Argonne", "DO NOT EDIT", "buildiface")):
            verbatim.append({"text": s[:200], "loc": i})

    bn = __import__("os").path.basename(path)
    if bn == "mpe_logf.h":
        what = (
            "Fortran include for MPE logging API: PARAMETER return codes and external integer symbols for "
            "MPE_Init_log through MPE_Finish_log."
        )
    elif bn == "mpif.h":
        what = (
            f"MPICH2 Fortran MPI include (machine-generated): PARAMETER constants and INTEGER/COMMON/SAVE "
            f"bindings. {len(lines)} lines; {len(constants)} PARAMETER entries; {len(entities)} entities."
        )
    else:
        what = f"Fortran include {bn}, {len(lines)} lines."

    if not verbatim and lines:
        verbatim.append({"text": lines[0].strip()[:200], "loc": 1})
    return dict(
        what_it_is=what,
        entities=entities,
        constants=constants,
        params_defined=[],
        equations=[],
        io=io,
        calls=[],
        verbatim_spans=verbatim[:5],
        unresolved=[],
    )

def extract_m4(lines: list[str], path: str) -> dict:
    entities = []
    constants = []
    calls = []
    io = []
    verbatim = []
    # AC_DEFUN([NAME], m4_define([NAME], m4_defun([NAME], AU_DEFUN([NAME], LT_OPTION_DEFINE
    re_def = re.compile(
        r"(?:AC_DEFUN|AU_DEFUN|m4_define|m4_defun)\s*\(\s*\[([^\]]+)\]"
    )
    re_def2 = re.compile(
        r"(?:AC_DEFUN|AU_DEFUN|m4_define|m4_defun)\s*\(\s*([A-Za-z0-9_]+)\s*,"
    )
    re_ltopt = re.compile(r"LT_OPTION_DEFINE\s*\(\s*\[([^\]]+)\]\s*,\s*\[([^\]]+)\]")
    seen_m = set()
    for i, line in enumerate(lines, 1):
        s = line.lstrip()
        m2 = re_ltopt.search(s)
        if m2:
            name = f"LT_OPTION_DEFINE {m2.group(1)}/{m2.group(2)}"
            if name not in seen_m:
                entities.append(f"{name} (L{i})")
                seen_m.add(name)
        for m in re_def.finditer(s):
            name = m.group(1)
            # skip LT_OPTION second-level false positives already handled
            key = name
            if key not in seen_m:
                entities.append(f"macro {name} (L{i})")
                seen_m.add(key)
        for m in re_def2.finditer(s):
            name = m.group(1)
            if name not in seen_m:
                entities.append(f"macro {name} (L{i})")
                seen_m.add(name)
        # m4_define([LT_PACKAGE_VERSION], [2.4.6])
        m = re.match(r"m4_define\(\[([^\]]+)\],\s*\[([^\]]*)\]\)", s)
